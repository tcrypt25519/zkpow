use super::{double, hash};

#[test]
fn empty_message() {
    assert_eq!(hash(b""), [
        0xe3, 0xb0, 0xc4, 0x42, 0x98, 0xfc, 0x1c, 0x14, 0x9a, 0xfb, 0xf4, 0xc8, 0x99, 0x6f, 0xb9, 0x24, 0x27, 0xae,
        0x41, 0xe4, 0x64, 0x9b, 0x93, 0x4c, 0xa4, 0x95, 0x99, 0x1b, 0x78, 0x52, 0xb8, 0x55,
    ]);
}

#[test]
fn abc() {
    assert_eq!(hash(b"abc"), [
        0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22, 0x23, 0xb0, 0x03,
        0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad,
    ]);
}

/// 56 bytes: the length field no longer fits after the terminator, so padding spills into a second block.
#[test]
fn spills_into_extra_block() {
    assert_eq!(hash(&[b'a'; 56]), [
        0xb3, 0x54, 0x39, 0xa4, 0xac, 0x6f, 0x09, 0x48, 0xb6, 0xd6, 0xf9, 0xe3, 0xc6, 0xaf, 0x0f, 0x5f, 0x59, 0x0c,
        0xe2, 0x0f, 0x1b, 0xde, 0x70, 0x90, 0xef, 0x79, 0x70, 0x68, 0x6e, 0xc6, 0x73, 0x8a,
    ]);
}

/// Exactly one block of input, where the padding block contains no message bytes at all.
#[test]
fn exact_block_multiple() {
    assert_eq!(hash(&[b'a'; 64]), [
        0xff, 0xe0, 0x54, 0xfe, 0x7a, 0xe0, 0xcb, 0x6d, 0xc6, 0x5c, 0x3a, 0xf9, 0xb6, 0x1d, 0x52, 0x09, 0xf4, 0x39,
        0x85, 0x1d, 0xb4, 0x3d, 0x0b, 0xa5, 0x99, 0x73, 0x37, 0xdf, 0x15, 0x46, 0x68, 0xeb,
    ]);
}

#[test]
fn double_matches_two_passes() {
    let message = [7u8; 80];
    assert_eq!(double(&message), hash(&hash(&message)));
}

#[test]
fn evaluates_at_compile_time() {
    const DIGEST: [u8; 32] = hash(b"abc");
    assert_eq!(DIGEST, hash(b"abc"));
}
